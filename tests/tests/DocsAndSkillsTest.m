function name = parentName(path)
    [~, name] = fileparts(path);
    name = string(name);
end

function blockText = missionTaskBlockText(text, taskStarts, taskEnds, taskIndex)
    if taskIndex < numel(taskStarts)
        blockEnd = taskStarts(taskIndex + 1) - 1;
    else
        blockEnd = strlength(text);
    end

    blockText = regexprep(extractBetween(text, taskEnds(taskIndex) + 1, blockEnd), "\s+", " ");
end

