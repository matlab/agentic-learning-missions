        function validatesContinuousAndDiscreteTimeSineWaveContract(testCase, Root)
            root = string(Root);
            missionPath = fullfile(root, "marketplace", "missions", ...
                "continuous-and-discrete-time", "mission.yaml");
            text = string(fileread(missionPath));
            testCase.verifyNotEmpty(regexp(text, '(?m)^version:\s*"1\.0\.1"\s*$', "once"), ...
                "Continuous and Discrete Time mission must increment to version 1.0.1");
            [taskStarts, taskEnds, taskTokens] = regexp(text, '(?m)^  - id:\s*"?(t\d{2})"?', ...
                "start", "end", "tokens");
            taskIds = string(cellfun(@(item) item{1}, taskTokens, UniformOutput=false));
            expectedPhrases = {
                "t01", ["Sine Wave block configured for continuous-time", "Sine Wave source", "continuous-time output"]
                "t02", ["same Sine Wave block", "positive finite sample interval", "Sine Wave source"]
                "t03", ["Sine Wave source to continuous-time output", "continuous-time Sine Wave source", "Sine Wave is continuous"]
                "t04", ["continuous Sine Wave output", "sampled signal derived from that Sine Wave", "continuous Sine Wave"]
                };

            for rowIndex = 1:size(expectedPhrases, 1)
                taskIndex = find(taskIds == expectedPhrases{rowIndex, 1}, 1);
                testCase.assertNotEmpty(taskIndex, "missing required mission task");
                blockText = missionTaskBlockText(text, taskStarts, taskEnds, taskIndex);
                for phrase = expectedPhrases{rowIndex, 2}
                    testCase.verifyTrue(contains(blockText, phrase), ...
                        taskIds(taskIndex) + " must consistently require a Sine Wave source: " + phrase);
                end
            end

            taskOneText = lower(missionTaskBlockText(text, taskStarts, taskEnds, 1));
            for forbiddenPhrase = ["any continuously varying signal source", "equivalent signal-producing subsystem"]
                testCase.verifyFalse(contains(taskOneText, forbiddenPhrase), ...
                    "t01 must not accept an alternate source: " + forbiddenPhrase);
            end
        end

